// 时间感数据：地球 46 亿年 → 24 小时（午夜 = 45.4 亿年前，此刻 = 24:00）
// 时间换算：24h / 45.4亿年；事件时刻 = 24 × (1 - 距今/45.4亿)
export const EARTH_YEARS = 4.54e9;
export const DAY_HOURS = 24;

export function yearsAgoToClock(yearsAgo) {
  return DAY_HOURS * (1 - yearsAgo / EARTH_YEARS);
}
export function fmtClock(h) {
  const hh = Math.floor(h), mm = Math.floor((h % 1) * 60), ss = Math.floor(((h * 60) % 1) * 60);
  return `${String(hh).padStart(2, '0')}:${String(mm).padStart(2, '0')}:${String(ss).padStart(2, '0')}`;
}

